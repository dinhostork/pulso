type Reply = Response | (() => Response | Promise<Response>);

/** Scripted product API keyed by `path?cursor`; the last queued reply repeats. */
function productServer(routes: Record<string, Reply[]>) {
  const queues = new Map(Object.entries(routes));
  return async ({ path, query }: ProductRequest) => {
    if (path === "/api/feed") return json(EMPTY_FEED);
    const cursor = query.get("cursor");
    const queue = queues.get(cursor ? `${path}?${cursor}` : path);
    if (!queue) return json({ code: "story_not_found", detail: "The Story was not found." }, 404);
    const reply = queue.length > 1 ? queue.shift()! : queue[0];
    return typeof reply === "function" ? reply() : reply.clone();
  };
}

async function open(routes: Record<string, Reply[]>, url: string) {
  const runtime = await storedSession("reader", productServer(routes));
  const app = await renderReadingApp(runtime, url);
  await waitFor(() => expect(runtime.controller.snapshot().status).toBe("authenticated"));
  return { runtime, app };
}

function calls(runtime: { productCalls: ProductRequest[] }, path: string) {
  return runtime.productCalls
    .filter((call) => call.path === path)
    .map((call) => call.query.get("cursor"));
}

async function endReached() {
  await fireEvent(screen.getByTestId("sources-list"), "endReached", { distanceFromEnd: 0 });
}

const FUTURE_FIELDS = [
  /timeline/i,
  /key points/i,
  /why it matters/i,
  /pulse/i,
  /opinion/i,
  /perspective/i,
  /recommended/i,
];

